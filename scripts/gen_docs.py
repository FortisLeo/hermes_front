#!/usr/bin/env python3
"""Generates docs/FEATURES.md: every Hermes skill group with its description, bridge tools and per-feature status.
Sources: hermes-skills/deskbot/*/SKILL.md, hermes-skills/tools.txt, docs/Feature status.md (run gen_feature_status.py first)."""
import os, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tools = [t.strip() for t in open(f"{root}/hermes-skills/tools.txt") if t.strip()]
status = {}
for line in open(f"{root}/docs/Feature status.md"):
    m = re.match(r"\| (\d+) \| (.*?) \| (\w+) \|", line)
    if m: status[int(m.group(1))] = (m.group(2), m.group(3))
ICON = {"BUILT": "built", "VERIFIED": "recipe verified", "PARTIAL": "partial", "SKILL": "recipe", "BLOCKED": "blocked"}
out = ["# Deskbot features", "", "Generated by `scripts/gen_docs.py` from the Hermes skills and `docs/Feature status.md`. Status words: **built** = implemented in the app/bridge and verified on the phone; **recipe verified** = the skill's key command ran on the phone; **partial** = part built; **recipe** = written, not yet run; **blocked** = needs hardware or modules this phone lacks.", ""]
tot = {}
for d in sorted(os.listdir(f"{root}/hermes-skills/deskbot")):
    text = open(f"{root}/hermes-skills/deskbot/{d}/SKILL.md").read()
    desc = re.search(r'description: "(.*?)"', text).group(1)
    nums = [int(n) for n in re.findall(r"^### (\d+) ", text, re.M)]
    used = sorted({t for t in tools if re.search(r"\b" + re.escape(t) + r"\b", text)})
    counts = {}
    for n in nums:
        s = status.get(n, ("", "SKILL"))[1]; counts[s] = counts.get(s, 0) + 1; tot[s] = tot.get(s, 0) + 1
    out.append(f"## {d.replace('-', ' ').title()}")
    out.append(f"{desc}")
    out.append("")
    out.append("Features: " + ", ".join(f"{v} {ICON[k]}" for k, v in sorted(counts.items(), key=lambda x: -x[1])) + f" ({len(nums)} total)")
    if used: out.append(""); out.append("Bridge tools: " + ", ".join(f"`{t}`" for t in used))
    out.append(""); out.append("| # | Feature | Status |"); out.append("| --- | --- | --- |")
    for n in nums:
        name, s = status.get(n, ("?", "SKILL")); out.append(f"| {n} | {name} | {ICON[s]} |")
    out.append("")
out.insert(3, "Totals: " + ", ".join(f"**{v}** {ICON[k]}" for k, v in sorted(tot.items(), key=lambda x: -x[1])) + f" of {sum(tot.values())} features. All {len(tools)} bridge tools: " + ", ".join(f"`{t}`" for t in sorted(tools)) + ".\n")
open(f"{root}/docs/FEATURES.md", "w").write("\n".join(out))
print("features:", sum(tot.values()), "tools:", len(tools))
